// Idioma e tema. O texto em português é a própria chave: o que não estiver no dicionário fica como está.
// Trocar de idioma recarrega a página, então os textos são resolvidos uma vez, na carga.
const ler = (k) => { try { return localStorage.getItem(k); } catch { return null; } };
const gravar = (k, v) => { try { localStorage.setItem(k, v); } catch { /* sem armazenamento: vale até recarregar */ } };

const escolhido = new URLSearchParams(location.search).get('lang') || ler('idioma') || (navigator.language.startsWith('pt') ? 'pt' : 'en');
export const lang = escolhido === 'en' ? 'en' : 'pt';

export function trocarIdioma() {
  const novo = lang === 'pt' ? 'en' : 'pt';
  gravar('idioma', novo);
  const url = new URL(location.href);
  url.searchParams.set('lang', novo); // também vale sem localStorage, e o link já abre no idioma
  location.replace(url);
}

export const temaAtual = () => document.documentElement.dataset.tema || 'escuro';
export function aplicarTema(tema) {
  document.documentElement.dataset.tema = tema;
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', tema === 'claro' ? '#f4f1ea' : '#0b0b0a');
  gravar('tema', tema);
}

export const t = (s) => (lang === 'en' && Object.hasOwn(EN, s) ? EN[s] : s);
// traduz todas as strings de uma estrutura de dados (ids e endereços não estão no dicionário)
export const traduzir = (v) => (typeof v === 'string' ? t(v)
  : Array.isArray(v) ? v.map(traduzir)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, traduzir(x)]))
  : v);

export function iniciarPagina() {
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
  if (temaAtual() === 'claro') aplicarTema('claro'); // cor da barra do navegador
  if (lang !== 'en') return;
  document.title = 'Victor Kauan · Portfolio';
  document.querySelector('meta[name="description"]')?.setAttribute('content', 'Victor Kauan, full-stack developer: from the ESP32 sensor to the phone app. VIA, TermoLOG, Vcall, SongV, duckV and other projects with their real screens.');
}

